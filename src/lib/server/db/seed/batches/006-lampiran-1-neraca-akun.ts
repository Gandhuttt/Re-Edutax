const akunId = (sektorKode: string, index: number) => `lampiran-1-neraca-akun-${sektorKode}-${index}`;

export const name = '006 lampiran 1 neraca akun (balance sheet transcript templates)';

export const run = async ({ db }: SeedContext) => {
	let seeded = 0;

	for (const template of templates) {
		const [sektorUsaha] = await db
			.select({ id: sektor_usaha_spt_pph_badan.id })
			.from(sektor_usaha_spt_pph_badan)
			.where(eq(sektor_usaha_spt_pph_badan.kode, template.sektorKode))
			.limit(1);

		if (!sektorUsaha) {
			throw new Error(`Sektor usaha "${template.sektorKode}" belum di-seed`);
		}

		for (const [index, [kode, nama, type, section, parentKode, sign]] of template.rows.entries()) {
			await db
				.insert(spt_pph_badan_lampiran_1_neraca_akun)
				.values({
					id: akunId(template.sektorKode, index),
					sektorUsahaId: sektorUsaha.id,
					nomorUrut: index + 1,
					kode,
					namaAkun: nama,
					rowType: type,
					section,
					parentKode: parentKode ?? null,
					sign: sign ?? null
				})
				.onConflictDoUpdate({
					target: spt_pph_badan_lampiran_1_neraca_akun.id,
					set: {
						nomorUrut: index + 1,
						kode,
						namaAkun: nama,
						rowType: type,
						section,
						parentKode: parentKode ?? null,
						sign: sign ?? null
					}
				});
			seeded += 1;
		}
	}

	console.log(`Seeded SPT PPh Badan references: ${seeded} lampiran 1 neraca akun rows`);

	return [];
};
