const akunId = (sektorKode: string, index: number) => `lampiran-1-akun-${sektorKode}-${index}`;

const classificationOf = (kode: string | null): 'income' | 'expense' | null => {
	if (!kode) return null;
	return kode.startsWith('4') ? 'income' : 'expense';
};

export const name = '005 lampiran 1 akun (laba rugi transcript templates)';

export const run = async ({ db }: SeedContext) => {
	let seeded = 0;

	for (const template of templates) {
		const [sektorUsaha] = await db
			.select({ id: sektor_usaha_spt_pph_badan.id })
			.from(sektor_usaha_spt_pph_badan)
			.where(eq(sektor_usaha_spt_pph_badan.kode, template.sektorKode))
			.limit(1);

		if (!sektorUsaha) {
			throw new Error(`Sektor usaha "${template.sektorKode}" belum di-seed`);
		}

		const statements = template.rows.map(([kode, nama, type, parentKode, sign, classificationOverride], index) => {
			const classification = type === 'data' ? (classificationOverride ?? classificationOf(kode)) : null;

			return db
				.insert(spt_pph_badan_lampiran_1_akun)
				.values({
					id: akunId(template.sektorKode, index),
					sektorUsahaId: sektorUsaha.id,
					nomorUrut: index + 1,
					kode,
					namaAkun: nama,
					rowType: type,
					classification,
					parentKode: parentKode ?? null,
					sign: sign ?? null
				})
				.onConflictDoUpdate({
					target: spt_pph_badan_lampiran_1_akun.id,
					set: {
						nomorUrut: index + 1,
						kode,
						namaAkun: nama,
						rowType: type,
						classification,
						parentKode: parentKode ?? null,
						sign: sign ?? null
					}
				});
		});
		await batchInsert(db, statements);
		seeded += template.rows.length;
	}

	console.log(`Seeded SPT PPh Badan references: ${seeded} lampiran 1 akun rows`);

	return [];
};
